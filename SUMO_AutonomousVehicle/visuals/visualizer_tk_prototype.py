import tkinter as tk

# ============================================================
# 1. CREATE THE MAIN APPLICATION WINDOW
# ============================================================

# Create the main Tkinter window.
# 'root' represents the entire GUI application.
root = tk.Tk()

# Set the title shown at the top of the window.
root.title("Autonomous Vehicle Path Tracking")

# Set the initial size of the window:
# width = 1200 pixels
# height = 700 pixels
root.geometry("1200x700")


# ============================================================
# 2. CREATE THE CANVAS
# ============================================================

# Canvas is the area where we draw the simulation visually.
#
# Later this will contain:
# - Road
# - Lane markings
# - Ego vehicle
# - Planned path
# - Destination
# - Actual trajectory
#
# At the moment we are building these components manually.

canvas = tk.Canvas(
    root,
    width=850,
    height=600,
    bg="lightgray"
)

# Place the Canvas inside the main window.
canvas.pack()


# ============================================================
# 3. DRAW THE ROAD
# ============================================================

# Draw a horizontal rectangular road.
#
# Coordinates:
# (50,250) ---------------- (800,250)
#    |                          |
#    |          ROAD            |
#    |                          |
# (50,350) ---------------- (800,350)

canvas.create_rectangle(
    50,       # left x-coordinate
    250,      # top y-coordinate
    800,      # right x-coordinate
    350,      # bottom y-coordinate
    fill="gray"
)


# ============================================================
# 4. DRAW LANE MARKINGS
# ============================================================

# Instead of manually drawing every dash,
# we use a loop.

# x will take values:
# 60, 100, 140, 180, ...
#
# Each iteration creates one small line.

for x in range(60, 800, 40):

    canvas.create_line(
        x,          # start x
        300,        # start y
        x + 20,     # end x
        300,        # end y
        fill="white",
        width=2
    )


# ============================================================
# 5. DEFINE THE EGO VEHICLE POSITION
# ============================================================

# These variables represent the CENTER of the vehicle.

# Current x-coordinate of the vehicle.
vehicle_x = 150

# Current y-coordinate of the vehicle.
vehicle_y = 300


# ============================================================
# 6. DRAW THE EGO VEHICLE
# ============================================================

# Draw a rectangle to represent the autonomous vehicle.
#
# The center of the vehicle is:
#
# (vehicle_x, vehicle_y)
#
# We draw 20 pixels on either side horizontally
# and 10 pixels on either side vertically.

vehicle = canvas.create_rectangle(
    vehicle_x - 20,
    vehicle_y - 10,
    vehicle_x + 20,
    vehicle_y + 10,
    fill="green"
)


# ============================================================
# 7. DEFINE THE DESTINATION
# ============================================================

# Destination coordinates.

target_x = 750
target_y = 300


# ============================================================
# 8. DRAW THE DESTINATION
# ============================================================

# Draw a red circle representing the target.

canvas.create_oval(
    target_x - 10,
    target_y - 10,
    target_x + 10,
    target_y + 10,
    fill="red"
)


# Add a text label above the destination.

canvas.create_text(
    target_x,
    target_y - 25,
    text="DESTINATION",
    fill="black"
)


# ============================================================
# 9. DRAW THE PLANNED PATH
# ============================================================

# Create a line from the current vehicle position
# to the destination.
#
# IMPORTANT:
# This is currently only a demonstration.
#
# It is NOT being calculated by the actual path-planning
# algorithm yet.
#
# Later this line will represent the route generated by
# our path planner.

planned_path = canvas.create_line(
    vehicle_x,
    vehicle_y,
    target_x,
    target_y,
    fill="blue",
    width=3,
    dash=(8, 4)
)


# ============================================================
# 10. FUNCTION TO UPDATE VEHICLE POSITION
# ============================================================

def update_vehicle_position():

    # Move the already-created vehicle rectangle
    # to its current coordinates.
    #
    # We do not create a new vehicle here.
    # We simply change the position of the existing one.

    canvas.coords(
        vehicle,

        # Left side of vehicle
        vehicle_x - 20,

        # Top side
        vehicle_y - 10,

        # Right side
        vehicle_x + 20,

        # Bottom side
        vehicle_y + 10
    )


# ============================================================
# 11. FUNCTION TO MOVE THE VEHICLE
# ============================================================

def update_vehicle():

    # vehicle_x is defined outside this function,
    # therefore we use 'global' because we want to modify it.
    global vehicle_x

    # --------------------------------------------------------
    # Move vehicle
    # --------------------------------------------------------

    # For now we simply move the vehicle 3 pixels to the right.
    #
    # IMPORTANT:
    # This is ONLY a temporary animation.
    #
    # The actual project will eventually receive the position
    # from SUMO through TraCI.

    vehicle_x += 3


    # --------------------------------------------------------
    # Update vehicle drawing
    # --------------------------------------------------------

    update_vehicle_position()


    # --------------------------------------------------------
    # Update planned path
    # --------------------------------------------------------

    # Since the vehicle moved, the beginning of the planned
    # path should move with it.

    canvas.coords(
        planned_path,
        vehicle_x,
        vehicle_y,
        target_x,
        target_y
    )


    # --------------------------------------------------------
    # Schedule the next update
    # --------------------------------------------------------

    # Run update_vehicle() again after 50 milliseconds.
    #
    # This creates the continuous animation.

    root.after(50, update_vehicle)


# ============================================================
# 12. START THE VEHICLE MOVEMENT
# ============================================================

# Call the function once.
#
# It will then repeatedly call itself using root.after().

update_vehicle()


# ============================================================
# 13. START TKINTER EVENT LOOP
# ============================================================

# mainloop() keeps the GUI running.
#
# Without this, the window would immediately close.

root.mainloop()